#!/usr/bin/env bash
set -e

CARGO_BIN="$HOME/.cargo/bin/cargo"
if ! command -v "$CARGO_BIN" &> /dev/null; then
    CARGO_BIN="cargo"
fi

echo "==> Building zenith-core wasm32 release..."
$CARGO_BIN build --target wasm32-unknown-unknown --release

mkdir -p wasm js
cp target/wasm32-unknown-unknown/release/zenith_core.wasm wasm/zenith_core.wasm

WASM_SIZE=$(ls -lh wasm/zenith_core.wasm | awk '{print $5}')
echo "==> WASM binary copied to wasm/zenith_core.wasm ($WASM_SIZE)"

echo "==> Generating js/wasm_inline.js base64 fallback for offline file:// protocol..."
B64=$(base64 < wasm/zenith_core.wasm | tr -d '\n')
cat <<EOF > js/wasm_inline.js
// Auto-generated by build.sh - Base64 fallback for local file:// execution
window.ZENITH_WASM_BASE64 = "$B64";
EOF

echo "==> Running unit tests..."
$CARGO_BIN test

echo "==> Build complete! Output: wasm/zenith_core.wasm ($WASM_SIZE)"
